/// Un-permute a candidate codeword into the caller-provided
/// `c_unperm` scratch buffer and CRC-verify it. Returns the
/// unpermuted full codeword + its first-`K` info slice as fresh
/// `Vec`s on CRC pass, or `None` if CRC fails (no allocation on
/// the fail path).
///
/// Caller provides the scratch buffer so it can be reused across
/// the ~4186 invocations a single OSD candidate triggers — heap
/// churn on each call was the dominant per-candidate cost before
/// this refactor (Gemini PR #86 review).
fn try_candidate_ldpc174_91(
    perm: &[usize],
    cp: &[u8],
    c_unperm: &mut [u8; LDPC_N],
) -> Option<(Vec<u8>, Vec<u8>)> {
    for col in 0..LDPC_N {
        c_unperm[perm[col]] = cp[col];
    }
    if !check_crc14(&c_unperm[..LDPC_K]) {
        return None;
    }
    Some((c_unperm[..LDPC_K].to_vec(), c_unperm.to_vec()))
}

/// Run the WSJT-X `nord=1 + npre1=1` pass against the given
/// [`OsdSetup`], updating [`OsdBest`] with any improvement.
///
/// `ntheta` selects which dispatch's gate threshold to apply
/// (10 for ndeep=2, 12 for ndeep=3 — see [`NPRE1_GATE_NDEEP2`] /
/// [`NPRE1_GATE_NDEEP3`]).
///
/// Mirrors `osd174_91.f90:179-228`. Also handles the order-0
/// baseline so callers don't need a separate "try order-0 first"
/// step — re-trying order-0 inside a multi-pass driver is harmless
/// (idempotent).
fn osd_npre1_pass(setup: &OsdSetup, best: &mut OsdBest, ntheta: u32) {
    let n = LDPC_N;
    let k = LDPC_K;
    let nt = NPRE1_PARITY_WINDOW.min(n - k);

    // Fixed-size scratch buffers: hoist allocations out of the per-
    // candidate hot loop (Gemini PR #87 review). `LDPC_N` / `LDPC_K`
    // are `const`, so `[T; N]` lives on the stack with no allocator
    // round-trip.
    let mut ce_iflag = [0u8; LDPC_N];
    let mut e2sub = [0u8; LDPC_N - LDPC_K];
    let mut e2 = [0u8; LDPC_N - LDPC_K];
    let mut ce_pair = [0u8; LDPC_N];
    // Caller-provided buffer for try_candidate_ldpc174_91 — shared
    // across every CRC try in this pass (Gemini PR #86 review,
    // ~4186 calls/candidate previously each allocating their own Vec).
    let mut c_unperm = [0u8; LDPC_N];

    // Order-0 baseline.
    {
        let mut wd = 0.0f32;
        for col in k..n {
            if setup.c_perm[col] != setup.hdec_perm[col] {
                wd += setup.absrx_perm[col];
            }
        }
        if wd < best.dd
            && let Some((d, cw)) =
                try_candidate_ldpc174_91(&setup.perm, &setup.c_perm, &mut c_unperm)
        {
            best.maybe_update(d, cw, wd);
        }
    }

    for iflag in (0..k).rev() {
        ce_iflag.copy_from_slice(&setup.c_perm);
        for col in 0..n {
            ce_iflag[col] ^= setup.g[iflag * n + col];
        }
        for j in 0..(n - k) {
            e2sub[j] = ce_iflag[k + j] ^ setup.hdec_perm[k + j];
        }
        let mut parity_err: u32 = 0;
        for j in 0..nt {
            parity_err += e2sub[j] as u32;
        }
        let d1 = setup.absrx_perm[iflag];

        // n1 = iflag baseline. WSJT-X gate is `parity_err + 1 <= ntheta`
        // (the +1 accounts for the iflag info-bit flip); written as
        // `parity_err < ntheta` to silence clippy::int_plus_one.
        if parity_err < ntheta {
            let mut parity_wd = 0.0f32;
            for j in 0..(n - k) {
                if e2sub[j] == 1 {
                    parity_wd += setup.absrx_perm[k + j];
                }
            }
            let dd = d1 + parity_wd;
            if dd < best.dd
                && let Some((d, cw)) =
                    try_candidate_ldpc174_91(&setup.perm, &ce_iflag, &mut c_unperm)
            {
                best.maybe_update(d, cw, dd);
            }
        }

        // n1 < iflag pair-anchor. e2 derived incrementally as
        // `e2sub XOR g[n1, k..n]` — WSJT-X `osd174_91:203`.
        for n1 in (0..iflag).rev() {
            for j in 0..(n - k) {
                e2[j] = e2sub[j] ^ setup.g[n1 * n + (k + j)];
            }
            let mut parity_err_pair: u32 = 0;
            for j in 0..nt {
                parity_err_pair += e2[j] as u32;
            }
            // +2 for the two info-bit flips (iflag + n1).
            if parity_err_pair + 2 > ntheta {
                continue;
            }
            ce_pair.copy_from_slice(&ce_iflag);
            for col in 0..n {
                ce_pair[col] ^= setup.g[n1 * n + col];
            }
            let mut parity_wd_pair = 0.0f32;
            for j in 0..(n - k) {
                if e2[j] == 1 {
                    parity_wd_pair += setup.absrx_perm[k + j];
                }
            }
            let dd = d1 + setup.absrx_perm[n1] + parity_wd_pair;
            if dd < best.dd
                && let Some((d, cw)) =
                    try_candidate_ldpc174_91(&setup.perm, &ce_pair, &mut c_unperm)
            {
                best.maybe_update(d, cw, dd);
            }
        }
    }
}

/// Hash table for the `npre2` pass. Maps an `ntau`-bit key
/// (XOR of two G columns, restricted to the first ntau parity rows)
/// to the chain of `(i1, i2)` MRB index pairs whose generator
/// difference yields that key.
///
/// Backed by three flat vecs (`fp` head-per-bucket, `pairs`/`next`
/// chained list). Mirrors WSJT-X `boxit91` (`osd174_91.f90:336-370`).
struct OsdNpre2Table {
    /// Per-hash-bucket head index into `pairs` (or `-1` = empty).
    fp: Vec<i32>,
    /// Chained `(i1, i2)` entries; `next[idx]` is the chained next or
    /// `-1` to terminate the bucket's chain.
    pairs: Vec<(u8, u8)>,
    next: Vec<i32>,
}

impl OsdNpre2Table {
    fn new(ntau: usize) -> Self {
        let buckets = 1usize << ntau;
        Self {
            fp: vec![-1; buckets],
            pairs: Vec::new(),
            next: Vec::new(),
        }
    }

    /// Head insertion: O(1) per insert. The previous implementation
    /// traversed the chain to find the tail (O(L) per insert), which
    /// dominated `build_npre2_table` for keys with long chains. To
    /// keep WSJT-X iteration order under `iter_pairs`, the build loop
    /// in [`build_npre2_table`] inserts entries in **reverse** of the
    /// original tail-insert order — head-insert then naturally yields
    /// the same traversal sequence. (Gemini PR #87 review.)
    fn insert(&mut self, key: usize, i1: u8, i2: u8) {
        let idx = self.pairs.len() as i32;
        self.pairs.push((i1, i2));
        self.next.push(self.fp[key]);
        self.fp[key] = idx;
    }

    /// Iterate over `(i1, i2)` pairs registered at `key`, in
    /// insertion order. Mirrors WSJT-X `fetchit91` chain traversal.
    fn iter_pairs(&self, key: usize) -> impl Iterator<Item = (u8, u8)> + '_ {
        let mut cur = self.fp[key];
        core::iter::from_fn(move || {
            if cur < 0 {
                None
            } else {
                let entry = self.pairs[cur as usize];
                cur = self.next[cur as usize];
                Some(entry)
            }
        })
    }
}

/// Build the [`OsdNpre2Table`] for `ntau`-bit XOR of all C(K, 2)
/// MRB column pairs.
///
/// Two perf optimisations vs the WSJT-X-faithful tail-insert / reverse-
/// loop reference (Gemini PR #87 review):
///
/// 1. **row_keys pre-compute.** Each row's `ntau`-bit parity key is
///    independent of the pairing inner loop. Hoist the per-row bit
///    pack into a `LDPC_K`-length scratch (~1.4 KB on the stack for
///    ntau=14 → `u16`), reducing the inner-loop work from O(K² · ntau)
///    to O(K · ntau + K²). `ntau <= 14` per WSJT-X constraints — fits
///    in `u16` with one bit to spare.
///
/// 2. **Forward loops paired with head-insert in
///    [`OsdNpre2Table::insert`].** The original reverse outer/inner +
///    tail-insert yielded a specific iteration order under
///    [`OsdNpre2Table::iter_pairs`]. Forward outer/inner + head-insert
///    yields the *same* order (head-insert reverses, forward loop
///    reverses again — net no change), so candidates surface in the
///    same sequence WSJT-X explores them. Preserves any tie-break
///    parity with the reference implementation.
fn build_npre2_table(setup: &OsdSetup, ntau: usize) -> OsdNpre2Table {
    let n = LDPC_N;
    let k = LDPC_K;
    let mut table = OsdNpre2Table::new(ntau);

    let mut row_keys = [0u16; LDPC_K];
    for i in 0..k {
        let mut rk: u16 = 0;
        // Hoist `i * n + k` out of the j loop — Gemini PR #96 minor
        // perf nit. `g` is row-major LDPC_K × LDPC_N, row i parity
        // section starts at `row_base + k`.
        let row_base = i * n;
        for j in 0..ntau {
            if setup.g[row_base + k + j] != 0 {
                rk |= 1u16 << (ntau - 1 - j);
            }
        }
        row_keys[i] = rk;
    }

    for i1 in 0..k {
        for i2 in 0..i1 {
            let key = (row_keys[i1] ^ row_keys[i2]) as usize;
            table.insert(key, i1 as u8, i2 as u8);
        }
    }
    table
}

/// Run the WSJT-X `npre2 = 1` pass (`osd174_91.f90:230-289`) against
/// the given [`OsdSetup`], updating [`OsdBest`] with any improvement.
///
/// For each MRB outer pattern (nord=1, so each `iflag` flip) and
/// each near-by perturbation `r2pat = e2sub XOR single-bit[i2]`
/// (`i2 = 0..=ntau`), look up which MRB pairs `(in1, in2)` produce a
/// G-column XOR matching `r2pat` in the precomputed table. Each match
/// yields a weight-3 candidate `me = m0 XOR misub XOR bit[in1] XOR
/// bit[in2]`; encode, weighted-distance, CRC-verify, update best.
///
/// The `sum(mi) < nord+npre1+npre2 = 3` guard skips matches whose
/// `in1` / `in2` overlap with `iflag` (would degenerate the
/// "weight-3 pattern" requirement).
fn osd_npre2_pass(setup: &OsdSetup, best: &mut OsdBest, ntau: usize) {
    let n = LDPC_N;
    let k = LDPC_K;
    let table = build_npre2_table(setup, ntau);

    // Same fixed-size scratch + caller-provided unperm buffer pattern
    // as `osd_npre1_pass` — see that function's hoist for rationale
    // (Gemini PR #86 / #87 review).
    let mut ce_misub = [0u8; LDPC_N];
    let mut e2sub = [0u8; LDPC_N - LDPC_K];
    let mut ce_test = [0u8; LDPC_N];
    let mut c_unperm = [0u8; LDPC_N];

    for iflag in (0..k).rev() {
        ce_misub.copy_from_slice(&setup.c_perm);
        for col in 0..n {
            ce_misub[col] ^= setup.g[iflag * n + col];
        }
        for j in 0..(n - k) {
            e2sub[j] = ce_misub[k + j] ^ setup.hdec_perm[k + j];
        }

        // Pack first `ntau` bits of e2sub into a base key.
        let mut base_key: usize = 0;
        for j in 0..ntau {
            if e2sub[j] != 0 {
                base_key |= 1 << (ntau - 1 - j);
            }
        }

        // i2 = 0 → r2pat = e2sub (no perturbation); i2 = 1..=ntau →
        // flip parity bit (i2-1).
        for i2 in 0..=ntau {
            let key = if i2 == 0 {
                base_key
            } else {
                base_key ^ (1 << (ntau - i2))
            };

            for (in1, in2) in table.iter_pairs(key) {
                let in1_u = in1 as usize;
                let in2_u = in2 as usize;
                // Threshold: sum(mi) >= nord + npre1 + npre2 = 3.
                // mi has bits at iflag, in1, in2; skip if any pair
                // overlaps (degenerates to weight-1 or weight-2).
                if iflag == in1_u || iflag == in2_u || in1_u == in2_u {
                    continue;
                }

                ce_test.copy_from_slice(&ce_misub);
                for col in 0..n {
                    ce_test[col] ^= setup.g[in1_u * n + col] ^ setup.g[in2_u * n + col];
                }

                let mut dd = 0.0f32;
                for col in 0..n {
                    if ce_test[col] != setup.hdec_perm[col] {
                        dd += setup.absrx_perm[col];
                    }
                }
                if dd < best.dd
                    && let Some((d, cw)) =
                        try_candidate_ldpc174_91(&setup.perm, &ce_test, &mut c_unperm)
                {
                    best.maybe_update(d, cw, dd);
                }
            }
        }
    }
}

/// Build an [`OsdResult`] from a populated [`OsdBest`] and the raw
/// (un-permuted) `llr`. Used by both `osd_decode_npre1` and
/// `osd_decode_npre1_npre2` to factor out the message77 / hard_errors
/// computation.
fn osd_result_from_best(llr: &[f32; LDPC_N], best: OsdBest) -> Option<OsdResult> {
    let (decoded, codeword) = best.state?;
    let mut hard_errors = 0u32;
    for i in 0..LDPC_N {
        if (codeword[i] == 1) != (llr[i] > 0.0) {
            hard_errors += 1;
        }
    }
    let mut message77 = [0u8; 77];
    message77.copy_from_slice(&decoded[..77]);
    Some(OsdResult {
        message77,
        info: decoded,
        codeword,
        hard_errors,
    })
}

/// WSJT-X-faithful `nord=1 + npre1=1` OSD decode (issue #63).
///
/// Mirrors `osd174_91.f90` with ndeep=2 — the FT8 default that
/// `ft8b.f90:405` dispatches to. Enumerates the same 4,186 weight-2
/// anchored-pair patterns our [`osd_decode`] does (order-1 baseline +
/// npre1 pair-anchor), but applies WSJT-X's `ntheta=10` early-reject
/// gate on partial parity-error count so only ~165 algebraically
/// plausible patterns reach the full encode + CRC verify.
///
/// **False-positive filter.** Pure brute-force `osd_decode` (ndeep=2)
/// occasionally returns CRC-luck codewords at high `nharderrors` — on
/// `qso3_busy.wav` it surfaces two confirmed phantoms (`N1API F2VX 73`
/// at 30 hard errors / -24 dB and `CQ EA2BFM IN83` at 31 / -24 dB).
/// These have parity errors spread broadly across all 83 parity bits,
/// so they trip the `ntheta=10` gate before reaching CRC and never
/// surface from this variant. Real low-SNR signals preserve the
/// algebraic structure of their parity bits and pass the gate.
///
/// The pattern enumeration matches WSJT-X line-for-line:
///   - Outer `iflag` walks from K-1 down to 0 (the 91 single-bit-flip
///     baseline patterns).
///   - Inner `n1` walks from `iflag` down to 0; when `n1 < iflag` the
///     pattern flips two MRB bits (`iflag`, `n1`) — the npre1
///     pair-anchor extension.
///   - The parity-error vector for the `n1 < iflag` case is computed
///     incrementally as `e2 = e2sub XOR g[n1, k..n]`, mirroring
///     `osd174_91:203`.
///
/// Returns `None` if no CRC-passing candidate is found.
pub fn osd_decode_npre1(llr: &[f32; LDPC_N]) -> Option<OsdResult> {
    let setup = osd_setup_ldpc174_91(llr)?;
    let mut best = OsdBest::new();
    osd_npre1_pass(&setup, &mut best, NPRE1_GATE_NDEEP2);
    osd_result_from_best(llr, best)
}

/// WSJT-X-faithful `nord=1 + npre1=1 + npre2=1` OSD decode
/// (= ndeep=3 dispatch).
///
/// Strictly extends [`osd_decode_npre1`]: runs the same npre1 pass
/// with a slightly looser `ntheta=12` gate (vs ndeep=2's 10), then
/// follows with the `npre2` second-stage pre-processing rule
/// (`osd174_91.f90:230-289`). npre2 explores weight-3 patterns that
/// the nord=1 search misses by looking up MRB-pair G-column XORs in a
/// `ntau=14` hash table, then anchoring on each (in1, in2) pair whose
/// generator difference cancels the parity-error vector of the test
/// pattern.
///
/// Pattern count vs other entries:
///
/// | entry | ndeep | raw patterns | post-gate (~) |
/// |---|---:|---:|---:|
/// | [`osd_decode`] | 2 | 4,186 | 4,186 (no gate) |
/// | [`osd_decode_deep`] | 3 | 121,667 | 121,667 (no gate) |
/// | [`osd_decode_npre1`] | 2 | 4,186 | ~165 |
/// | this | 3 | ~127,000 | ~165 + ~few-thousand npre2 |
///
/// Caller dispatch typically routes higher-`q` (cleaner) candidates
/// to ndeep=3 since the npre2 pass costs a 64 KB hash-table build
/// up-front; not worth it on every candidate.
pub fn osd_decode_npre1_npre2(llr: &[f32; LDPC_N]) -> Option<OsdResult> {
    let setup = osd_setup_ldpc174_91(llr)?;
    let mut best = OsdBest::new();
    // ndeep=3 uses ntheta=12 (vs ndeep=2's 10) — looser gate because
    // the npre2 pass below picks up patterns this would have rejected.
    osd_npre1_pass(&setup, &mut best, NPRE1_GATE_NDEEP3);
    osd_npre2_pass(&setup, &mut best, NPRE2_NTAU);
    osd_result_from_best(llr, best)
}

/// Packed-elimination setup for [`osd_decode_generic`], generic over
/// [`LdpcParams`] — the same technique `osd_setup_ldpc174_91` applies
/// to FT8's specific LDPC(174,91), made reusable across every code
/// that shares the generic path (MSK144's LDPC(128,90), uvpacket's
/// LDPC(240,101), FST4).
///
/// Returns `(perm, g, pivot_col)` — identical shape and identical
/// values to what `osd_decode_generic` used to compute inline (steps
/// 1-3): `perm` the reliability-descending column order, `g` the
/// row-reduced generator in byte-per-bit form (every downstream
/// consumer — order-0 encode, `try_candidate`, the `k1..k4` search —
/// is unchanged and still reads `g` this way), `pivot_col[r]` the
/// permuted-space column that row `r` pivoted on.
///
/// **Row-swap elimination, not column-swap** — this is the one place
/// this function's packing differs in *shape* from `osd_setup_
/// ldpc174_91`'s, because the algorithm it is packing differs: this
/// crate's generic path scans columns left-to-right and swaps *rows*
/// into place (`g.swap(r, pivot_row)` below), where FT8's own
/// `osd_setup_ldpc174_91` fixes each row in turn and swaps *columns*.
/// Both reach a valid RREF; they are not required to (and in general
/// won't) select the same pivot positions, so this function does not
/// try to reproduce FT8's specific choice — it packs *this* function's
/// existing algorithm, unchanged, which is what
/// `osd_generic_setup_matches_reference` (this module's test suite)
/// verifies against the pre-packing implementation kept there as a
/// reference.
///
/// Row-swap turns out to be the easier case to pack: swapping two
/// entire packed rows is one `Vec::swap` call, versus the per-bit
/// extract-and-set a column swap needs (see `osd_decode_packed` in
/// `wspr::osd` for that harder case, packing WSPR's column-swap
/// elimination). The row XOR during elimination — this function's
/// hottest inner loop, up to `k·(k−1)` times — is the same class of
/// win either way: `n.div_ceil(64)` word-XORs instead of `n` per-byte
/// ones.
fn osd_setup_generic_packed<P: LdpcParams>(
    llr: &[f32],
) -> Option<(Vec<usize>, Vec<u8>, Vec<usize>)> {
    let n = P::N;
    let k = P::K;
    let words = n.div_ceil(64);

    let mut perm: Vec<usize> = (0..n).collect();
    perm.sort_unstable_by(|&a, &b| {
        llr[b]
            .abs()
            .partial_cmp(&llr[a].abs())
            .unwrap_or(core::cmp::Ordering::Equal)
    });

    let mut g_packed: Vec<Vec<u64>> = vec![vec![0u64; words]; k];
    for row in 0..k {
        for col in 0..n {
            let j = perm[col];
            let bit = if j < k {
                (row == j) as u64
            } else {
                P::gen_parity(j - k, row) as u64
            };
            if bit == 1 {
                g_packed[row][col / 64] |= 1 << (col % 64);
            }
        }
    }

    let mut pivot_col: Vec<usize> = vec![0; k];
    let mut pivot_row = 0usize;
    for col in 0..n {
        if pivot_row >= k {
            break;
        }
        let word = col / 64;
        let bit = col % 64;
        let mut found: Option<usize> = None;
        for r in pivot_row..k {
            if (g_packed[r][word] >> bit) & 1 != 0 {
                found = Some(r);
                break;
            }
        }
        let Some(r) = found else { continue };
        if r != pivot_row {
            g_packed.swap(r, pivot_row);
        }
        let pivot = g_packed[pivot_row].clone();
        for r2 in 0..k {
            if r2 != pivot_row && (g_packed[r2][word] >> bit) & 1 != 0 {
                for c in 0..words {
                    g_packed[r2][c] ^= pivot[c];
                }
            }
        }
        pivot_col[pivot_row] = col;
        pivot_row += 1;
    }

    if pivot_row < k {
        return None; // degenerate (shouldn't happen with a valid LDPC code)
    }

    // Unpack to the byte-per-bit format every downstream consumer
    // expects — one linear O(k*n) pass, negligible next to the O(k²*n)
    // elimination it replaces.
    let mut g: Vec<u8> = vec![0u8; k * n];
    for row in 0..k {
        for col in 0..n {
            g[row * n + col] = ((g_packed[row][col / 64] >> (col % 64)) & 1) as u8;
        }
    }

    Some((perm, g, pivot_col))
}

/// Generic OSD with configurable order, parameterised over [`LdpcParams`].
///
/// `ndeep`: search depth (1..=4). `k4_limit`: upper bound (exclusive)
/// on bit indices used in the order-4 extension; ignored when
/// `ndeep < 4`. `verify`: parity-converged candidate filter; pass
/// `Some(check_crc)` for codecs whose info bits include an inline
/// integrity field, `None` to accept any parity-valid candidate.
///
/// Algorithm identical to the WSJT-X reference; only the working
/// buffer shapes are runtime-sized to accommodate either LDPC code.
pub fn osd_decode_generic<P: LdpcParams>(
    llr: &[f32],
    ndeep: u8,
    k4_limit: usize,
    verify: Option<fn(&[u8]) -> bool>,
) -> Option<OsdResult> {
    debug_assert_eq!(llr.len(), P::N, "llr length must equal P::N");

    let n = P::N;
    let k = P::K;

    // Steps 1-3 (sort, build, GF(2) eliminate) live in
    // `osd_setup_generic_packed` — see its doc comment for why this
    // is a packed *representation* of exactly the same row-swap
    // elimination this function used to run inline, not a different
    // algorithm. Everything from here on (order-0 encode, the k1..k4
    // search, `try_candidate`) is unchanged and still consumes `g` as
    // plain byte-per-bit, exactly as before.
    let Some((perm, g, pivot_col)) = osd_setup_generic_packed::<P>(llr) else {
        return None; // degenerate (shouldn't happen with a valid LDPC code)
    };

    // Fixed-size scratch, sized with headroom for the largest
    // `LdpcParams` this function serves today (FST4's `N=240`) —
    // avoids a heap alloc/dealloc round-trip on every one of
    // `try_and_update`'s ~166 650 calls for an order-3 FST4 search
    // (issue #306 follow-up: measured 6.28 s/candidate for OSD on
    // real embedded hardware, most of that spent on candidates that
    // fail CRC immediately). `[u8; P::N]` isn't expressible here —
    // `P::N` is a trait-associated const, and stable Rust can't use a
    // generic parameter's associated const as an array length
    // (`generic_const_exprs` remains nightly-only) — so this uses the
    // same "fixed max bound + runtime-length prefix slice" idiom
    // `engine::llr`'s `MAX_NSYM`/`MAX_IBMAX_PLUS_1` already established
    // for the identical problem.
    const OSD_MAX_N: usize = 256; // ≥ 240 (FST4), 174 (FT8), 128 (MSK144)

    // ── Step 4: hard decisions on MRB bits ──────────────────────────
    let mut mrb = [0u8; OSD_MAX_N];
    let mrb = &mut mrb[..k];
    for r in 0..k {
        let orig = perm[pivot_col[r]];
        mrb[r] = if llr[orig] > 0.0 { 1 } else { 0 };
    }

    // ── Step 5: encode order-0 candidate ────────────────────────────
    let mut c_perm = [0u8; OSD_MAX_N];
    let c_perm = &mut c_perm[..n];
    for r in 0..k {
        if mrb[r] == 1 {
            for col in 0..n {
                c_perm[col] ^= g[r * n + col];
            }
        }
    }

    // Permuted hard-decisions and |LLR| — depend only on `perm`/`llr`,
    // both fixed for the rest of this call, so precomputing them once
    // here (O(n)) instead of inside `try_and_update` removes a branch,
    // an `.abs()` call and a double indirection (`llr[perm[col]]`)
    // from the ~166,650-call weighted-distance loop below (issue #306
    // follow-up: the previous per-call heap-alloc fix left this
    // redundant recomputation in place — same closure, different
    // waste). Bit-identical: `try_and_update` used to compute exactly
    // these two values fresh on every call from the same unchanging
    // `perm`/`llr`.
    let mut hdec_perm = [0u8; OSD_MAX_N];
    let hdec_perm = &mut hdec_perm[..n];
    let mut absrx_perm = [0.0f32; OSD_MAX_N];
    let absrx_perm = &mut absrx_perm[..n];
    for col in 0..n {
        hdec_perm[col] = if llr[perm[col]] > 0.0 { 1u8 } else { 0u8 };
        absrx_perm[col] = llr[perm[col]].abs();
    }

    // Inverse permutation: `inv_perm[i]` is the permuted-space column
    // holding unpermuted (systematic) position `i`. `decoded[i]` for
    // `i < k` only ever needs `cp[inv_perm[i]]` — this lets
    // `try_and_update` gather just the `k` bits `verify` needs instead
    // of scattering the full `n`-length codeword (and copying its
    // first `k`) on every call before even checking whether `verify`
    // will reject the candidate a moment later. `verify` (`check_crc14`
    // and its FST4/MSK144 equivalents) is a strong filter — a
    // 14..24-bit CRC rejects essentially every one of the ~166,650
    // wrong FST4 candidates — so this turns the previously
    // always-executed `O(n)` scatter into an `O(k)` gather for the
    // overwhelming majority of calls, deferring the `O(n)` codeword
    // build to the rare (effectively: only the true candidate) path
    // that actually needs it.
    let mut inv_perm = [0usize; OSD_MAX_N];
    let inv_perm = &mut inv_perm[..n];
    for (col, &p) in perm.iter().enumerate() {
        inv_perm[p] = col;
    }

    // Best-so-far, plus the scratch `try_and_update` writes each
    // candidate into before deciding whether it's an improvement.
    // Single closure (not a `try_candidate` + separate `update_best`
    // pair) so there's exactly one `FnMut` capturing all of these by
    // mutable reference, rather than two closures each needing to
    // borrow the other's captures — simpler for the borrow checker,
    // same logic as the previous two-closure version.
    let mut best_wd: Option<f32> = None;
    let mut best_codeword = [0u8; OSD_MAX_N];
    let mut best_decoded = [0u8; OSD_MAX_N];
    let mut scratch_c = [0u8; OSD_MAX_N];
    let mut scratch_decoded = [0u8; OSD_MAX_N];
    let mut try_and_update = |cp: &[u8]| {
        let decoded = &mut scratch_decoded[..k];
        for (i, d) in decoded.iter_mut().enumerate() {
            *d = cp[inv_perm[i]];
        }
        if let Some(f) = verify
            && !f(decoded)
        {
            return;
        }
        let c = &mut scratch_c[..n];
        for col in 0..n {
            c[perm[col]] = cp[col];
        }
        let mut wd = 0.0f32;
        for col in 0..n {
            if cp[col] != hdec_perm[col] {
                wd += absrx_perm[col];
            }
        }
        if best_wd.is_none_or(|bd| wd < bd) {
            best_wd = Some(wd);
            best_codeword[..n].copy_from_slice(&scratch_c[..n]);
            best_decoded[..k].copy_from_slice(&scratch_decoded[..k]);
        }
    };

    // Order-0.
    try_and_update(c_perm);

    // Orders 1..ndeep: flip 1, 2, …, ndeep MRB bits. Reuse buffers
    // across iterations to avoid per-candidate Vec allocs.
    let mut c1 = [0u8; OSD_MAX_N];
    let c1 = &mut c1[..n];
    let mut c2 = [0u8; OSD_MAX_N];
    let c2 = &mut c2[..n];
    let mut c3 = [0u8; OSD_MAX_N];
    let c3 = &mut c3[..n];
    let mut c4 = [0u8; OSD_MAX_N];
    let c4 = &mut c4[..n];
    for k1 in 0..k {
        c1.copy_from_slice(c_perm);
        for col in 0..n {
            c1[col] ^= g[k1 * n + col];
        }
        try_and_update(c1);
        if ndeep < 2 {
            continue;
        }
        for k2 in (k1 + 1)..k {
            c2.copy_from_slice(c1);
            for col in 0..n {
                c2[col] ^= g[k2 * n + col];
            }
            try_and_update(c2);
            if ndeep < 3 {
                continue;
            }
            for k3 in (k2 + 1)..k {
                c3.copy_from_slice(c2);
                for col in 0..n {
                    c3[col] ^= g[k3 * n + col];
                }
                try_and_update(c3);
                if ndeep >= 4 && k3 + 1 < k4_limit {
                    for k4 in (k3 + 1)..k4_limit.min(k) {
                        c4.copy_from_slice(c3);
                        for col in 0..n {
                            c4[col] ^= g[k4 * n + col];
                        }
                        try_and_update(c4);
                    }
                }
            }
        }
    }

    // ── Step 6: return best ─────────────────────────────────────────
    best_wd?;
    let codeword = &best_codeword[..n];
    let decoded = &best_decoded[..k];
    let mut hard_errors = 0u32;
    for i in 0..n {
        if (codeword[i] == 1) != (llr[i] > 0.0) {
            hard_errors += 1;
        }
    }
    let mut message77 = [0u8; 77];
    message77.copy_from_slice(&decoded[..77]);
    Some(OsdResult {
        message77,
        info: decoded.to_vec(),
        codeword: codeword.to_vec(),
        hard_errors,
    })
}

