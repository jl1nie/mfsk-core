/// Packed-elimination setup for [`osd_decode_generic`], generic over
/// [`LdpcParams`] (MSK144's LDPC(128,90), and the order-1..4 searches
/// diagnostics run on the other codes).
///
/// Returns `(perm, g, pivot_col)` — identical shape and identical
/// values to what `osd_decode_generic` used to compute inline (steps
/// 1-3): `perm` the reliability-descending column order, `g` the
/// row-reduced generator in byte-per-bit form (every downstream
/// consumer — order-0 encode, `try_candidate`, the `k1..k4` search —
/// is unchanged and still reads `g` this way), `pivot_col[r]` the
/// permuted-space column that row `r` pivoted on.
///
/// **Row-swap elimination, not column-swap**: this scans columns
/// left-to-right and swaps *rows* into place (`g.swap(r, pivot_row)`
/// below), taking the first `k` independent columns. WSJT-X fixes each
/// row in turn and swaps *columns* within `id..k+20`
/// ([`super::osd_npre`]), which can choose a different basis, so this is
/// not upstream's; it packs *this* function's
/// existing algorithm, unchanged, which is what
/// `osd_generic_setup_matches_reference` (this module's test suite)
/// verifies against the pre-packing implementation kept there as a
/// reference.
///
/// Row-swap turns out to be the easier case to pack: swapping two
/// entire packed rows is one `Vec::swap` call, versus the per-bit
/// extract-and-set a column swap needs (see `osd_decode_packed` in
/// `wspr::osd` for that harder case, packing WSPR's column-swap
/// elimination). The row XOR during elimination — this function's
/// hottest inner loop, up to `k·(k−1)` times — is the same class of
/// win either way: `n.div_ceil(64)` word-XORs instead of `n` per-byte
/// ones.
fn osd_setup_generic_packed<P: LdpcParams>(
    llr: &[f32],
) -> Option<(Vec<usize>, Vec<u8>, Vec<usize>)> {
    let n = P::N;
    let k = P::K;
    let words = n.div_ceil(64);

    let mut perm: Vec<usize> = (0..n).collect();
    perm.sort_unstable_by(|&a, &b| {
        llr[b]
            .abs()
            .partial_cmp(&llr[a].abs())
            .unwrap_or(core::cmp::Ordering::Equal)
    });

    let mut g_packed: Vec<Vec<u64>> = vec![vec![0u64; words]; k];
    for row in 0..k {
        for col in 0..n {
            let j = perm[col];
            let bit = if j < k {
                (row == j) as u64
            } else {
                P::gen_parity(j - k, row) as u64
            };
            if bit == 1 {
                g_packed[row][col / 64] |= 1 << (col % 64);
            }
        }
    }

    let mut pivot_col: Vec<usize> = vec![0; k];
    let mut pivot_row = 0usize;
    for col in 0..n {
        if pivot_row >= k {
            break;
        }
        let word = col / 64;
        let bit = col % 64;
        let mut found: Option<usize> = None;
        for r in pivot_row..k {
            if (g_packed[r][word] >> bit) & 1 != 0 {
                found = Some(r);
                break;
            }
        }
        let Some(r) = found else { continue };
        if r != pivot_row {
            g_packed.swap(r, pivot_row);
        }
        let pivot = g_packed[pivot_row].clone();
        for r2 in 0..k {
            if r2 != pivot_row && (g_packed[r2][word] >> bit) & 1 != 0 {
                for c in 0..words {
                    g_packed[r2][c] ^= pivot[c];
                }
            }
        }
        pivot_col[pivot_row] = col;
        pivot_row += 1;
    }

    if pivot_row < k {
        return None; // degenerate (shouldn't happen with a valid LDPC code)
    }

    // Unpack to the byte-per-bit format every downstream consumer
    // expects — one linear O(k*n) pass, negligible next to the O(k²*n)
    // elimination it replaces.
    let mut g: Vec<u8> = vec![0u8; k * n];
    for row in 0..k {
        for col in 0..n {
            g[row * n + col] = ((g_packed[row][col / 64] >> (col % 64)) & 1) as u8;
        }
    }

    Some((perm, g, pivot_col))
}

/// The (240,101) code as `osd240_101.f90` searches it: only the first `keff`
/// information bits are free, and the last `101 - keff` CRC bits are
/// cascaded with the LDPC code instead of being searched.
///
/// `osd240_101.f90`'s header: "the first `p1 = k - 77` bits of the CRC24 are used
/// for bad-codeword detection, the last `p2 = 101 - k` are cascaded with the
/// LDPC code for the purpose of improving the distance spectrum". Its generator
/// row `i <= 77` is the message unit vector *with its CRC computed*, then the
/// bits `78..=k` zeroed (they are free bits now); rows `78..=k` are unit vectors
/// of those free CRC bits; there are no rows for the cascaded ones. FST4 calls it
/// with `Keff = 91` (`fst4_decode.f90:478`), so the search runs over a
/// (240,91) subcode of the (240,101) code, 2^10 times fewer codewords than the
/// full code, all of which agree with the message on ten of the CRC's 24 bits.
///
/// Measured (upstream `decode240_101` itself, BPSK/AWGN LLRs, ndeep 2, 4000
/// draws a point, one `Keff` per process): `Keff = 91` recovers 3432 / 2071 / 593
/// at amplitude 1.0 / 0.9 / 0.8 where `Keff = 101` recovers 2903 / 1231 / 211 —
/// about 0.5 dB. This crate searched `Keff = 101` (`P::K`) until #456.
#[derive(Clone, Copy)]
pub struct PartialCrc {
    /// `Keff`: the number of free information bits, in `77..=101`.
    pub keff: usize,
    /// The 101-bit info word for a 77-bit message: the message and its CRC-24
    /// (`ldpc240_101::append_crc24`).
    pub with_crc: fn(&[u8; 77]) -> [u8; 101],
}

/// Counts how many patterns WSJT-X's actual `npre1` pre-screening
/// mechanism (`osd240_101.f90`/`osd174_91.f90`'s `nord=1, npre1=1`
/// loop, `nt=40`/`ntheta=12` partial-parity gate) would attempt and
/// pass for a given LLR array — without doing the expensive full
/// codeword construction for gate-passing patterns, only counting
/// them. Issue #306 follow-up (VK3NV): "a cheap indication of the
/// ceiling" — how much smaller is WSJT-X's actual pruned search than
/// `osd_decode_generic`'s unpruned order-3 combinatorial one — before
/// committing to the full genericised port of `npre1`/`npre2`.
///
/// Mirrors `osd240_101.f90` lines 177-203 exactly: for each single-bit
/// "anchor" position `p` (0-based, `0..k`, matching WSJT-X's `iflag`
/// 1-based `1..k`), the "pure" single flip (`n1 == p`, one call
/// equivalent to a real `mrbencode101` — counted here, not performed)
/// plus every second flip `n1 < p` computed incrementally by XORing
/// the single-flip base's parity mismatch against row `n1`'s own
/// parity portion — the same linearity `osd240_101.f90` exploits
/// (`e2 = e2sub XOR g2(k+1:N, n1)`), so no re-encoding is needed per
/// `n1`. Reuses this module's own [`osd_setup_generic_packed`] for the
/// permutation/RREF/order-0 setup — the same code
/// `osd_decode_generic`'s combinatorial search already uses, so the
/// two counts are on equal footing (same reliability ranking, same
/// order-0 baseline).
///
/// Returns `(ntotal, npostgate)`: `ntotal` is the total pattern count
/// attempted (compare against `osd_decode_generic`'s unpruned
/// `C(k,3)` for the equivalent order — this function only replicates
/// the `nord=1` pass, i.e., the ndeep=2/3 count, not `npre2`'s
/// additional weight-3 hash-table pass); `npostgate` is how many of
/// those actually clear the `ntheta` gate and would reach the
/// expensive step in the real algorithm.
#[cfg(feature = "internal-testing")]
pub fn npre1_pattern_counts<P: LdpcParams>(llr: &[f32]) -> Option<(u32, u32)> {
    const NT: usize = 40; // osd240_101.f90/osd174_91.f90 shared constant
    const NTHETA: u32 = 12; // FST4's ndeep=2 and ndeep=3 both use 12

    let n = P::N;
    let k = P::K;
    let (perm, g, pivot_col) = osd_setup_generic_packed::<P>(llr)?;

    let mut hdec = alloc::vec![0u8; n];
    for (col, h) in hdec.iter_mut().enumerate() {
        *h = if llr[perm[col]] > 0.0 { 1 } else { 0 };
    }
    let mut mrb = alloc::vec![0u8; k];
    for (r, m) in mrb.iter_mut().enumerate() {
        let orig = perm[pivot_col[r]];
        *m = if llr[orig] > 0.0 { 1 } else { 0 };
    }
    let mut c0 = alloc::vec![0u8; n];
    for (r, &mr) in mrb.iter().enumerate() {
        if mr == 1 {
            for (col, c) in c0.iter_mut().enumerate() {
                *c ^= g[r * n + col];
            }
        }
    }

    let window = NT.min(n - k);
    let mut ntotal = 0u32;
    let mut npostgate = 0u32;
    let mut e2sub = alloc::vec![0u8; n - k];

    for p in 0..k {
        // n1 == p: the "pure" single-bit flip.
        for i in 0..(n - k) {
            e2sub[i] = (c0[k + i] ^ g[p * n + k + i]) ^ hdec[k + i];
        }
        let mismatches: u32 = e2sub[..window].iter().map(|&b| b as u32).sum();
        ntotal += 1;
        if mismatches < NTHETA {
            npostgate += 1;
        }

        // n1 < p: incremental second flip, matching osd240_101.f90's
        // `e2 = ieor(e2sub, g2(k+1:N,n1))` -- always against the
        // single-flip base `e2sub`, not chained across `n1`.
        for n1 in (0..p).rev() {
            let mismatches: u32 = (0..window)
                .map(|i| (e2sub[i] ^ g[n1 * n + k + i]) as u32)
                .sum();
            ntotal += 1;
            if mismatches + 2 <= NTHETA {
                npostgate += 1;
            }
        }
    }

    Some((ntotal, npostgate))
}

/// Generic OSD with configurable order, parameterised over [`LdpcParams`].
///
/// `ndeep`: search depth (1..=4). `k4_limit`: bound on bit indices used
/// in the order-4 extension; ignored when `ndeep < 4`. `verify`:
/// parity-converged candidate filter; pass `Some(check_crc)` for codecs
/// whose info bits include an inline integrity field, `None` to accept
/// any parity-valid candidate.
///
/// `k4_tail`: which end of the MRB reliability ordering `k4_limit`
/// bounds. Row index in `0..k` runs from the *most* reliable MRB bit
/// (row 0) to the *least* reliable (row `k-1`) — confirmed empirically
/// (issue #306 follow-up), not just asserted: a synthetic strictly-
/// monotonic LLR fed through this function's own setup showed
/// `|llr|` decreasing monotonically from row 0 to row `k-1`. `false`
/// (existing behaviour, every current caller): `k4` ranges over
/// `0..k4_limit` — the *most* reliable end — and the extension only
/// fires when `k1`/`k2`/`k3` are themselves within that same range
/// (transitively, via `k1<k2<k3`). `true`: `k4` ranges over
/// `(k-k4_limit)..k` instead — the *least* reliable end, matching this
/// stated intent of the since-removed `osd_decode_deep4` wrapper ("restricting k4 to the tail... because errors concentrate
/// in low-|LLR| bits") — which the `false` behaviour does not actually
/// implement, despite the doc comment describing it. Added to test
/// that discrepancy directly (issue #306 follow-up, prompted while
/// investigating FST4 OSD costs) rather than assume either direction;
/// `false` for every caller until that AWGN sweep decides one way.
///
/// Algorithm identical to the WSJT-X reference otherwise; only the
/// working buffer shapes are runtime-sized to accommodate either LDPC
/// code.
pub fn osd_decode_generic<P: LdpcParams>(
    llr: &[f32],
    ndeep: u8,
    k4_limit: usize,
    verify: Option<fn(&[u8]) -> bool>,
    k4_tail: bool,
) -> Option<OsdResult> {
    debug_assert_eq!(llr.len(), P::N, "llr length must equal P::N");

    let n = P::N;
    let k = P::K;

    // Steps 1-3 (sort, build, GF(2) eliminate) live in
    // `osd_setup_generic_packed` — see its doc comment for why this
    // is a packed *representation* of exactly the same row-swap
    // elimination this function used to run inline, not a different
    // algorithm. Everything from here on (order-0 encode, the k1..k4
    // search, `try_candidate`) used to consume `g` as plain
    // byte-per-bit throughout; see the `g_packed` repacking below for
    // why that's no longer true of the row-XOR construction specifically.
    let Some((perm, g, pivot_col)) = osd_setup_generic_packed::<P>(llr) else {
        return None; // degenerate (shouldn't happen with a valid LDPC code)
    };

    // Fixed-size scratch, sized with headroom for the largest
    // `LdpcParams` this function serves today (FST4's `N=240`) —
    // avoids a heap alloc/dealloc round-trip on every one of
    // `try_and_update`'s ~166 650 calls for an order-3 FST4 search
    // (issue #306 follow-up: measured 6.28 s/candidate for OSD on
    // real embedded hardware, most of that spent on candidates that
    // fail CRC immediately). `[u8; P::N]` isn't expressible here —
    // `P::N` is a trait-associated const, and stable Rust can't use a
    // generic parameter's associated const as an array length
    // (`generic_const_exprs` remains nightly-only) — so this uses the
    // same "fixed max bound + runtime-length prefix slice" idiom
    // `engine::llr`'s `MAX_NSYM`/`MAX_IBMAX_PLUS_1` already established
    // for the identical problem.
    const OSD_MAX_N: usize = 256; // ≥ 240 (FST4), 174 (FT8), 128 (MSK144)
    const OSD_WORDS: usize = OSD_MAX_N.div_ceil(64); // 4

    // ── Step 4: hard decisions on MRB bits ──────────────────────────
    let mut mrb = [0u8; OSD_MAX_N];
    let mrb = &mut mrb[..k];
    for r in 0..k {
        let orig = perm[pivot_col[r]];
        mrb[r] = if llr[orig] > 0.0 { 1 } else { 0 };
    }

    // Pack `g` (byte-per-bit, from `osd_setup_generic_packed` above)
    // into `OSD_WORDS`-word rows, once, up front — O(k*n), negligible
    // next to what it feeds. `osd_setup_generic_packed` itself already
    // builds and Gaussian-eliminates a packed representation
    // internally, then unpacks it to byte-per-bit before returning
    // (its own doc comment explains why: `packed_setup_differential`'s
    // tests check it against a byte-per-bit reference, and no other
    // caller needs the packed form — until now). Re-packing here,
    // rather than changing what `osd_setup_generic_packed` returns,
    // keeps that function's tested contract untouched and confines
    // this change to the one consumer that actually has a hot loop
    // over `g`: every one of the ~166 650 combinatorial candidates
    // XORs one full `g` row into a running codeword (`c1[col] ^=
    // g[k1*n+col]` for `col in 0..n`, and again for `c2`/`c3`/`c4`) —
    // unlike `try_and_update`'s scatter (moved behind the `verify`
    // gate above), this construction *is* the candidate, so it can't
    // be deferred, only made cheaper per call. No permutation is
    // involved here (both `c*` and `g`'s rows are already in the same
    // permuted-column order), so — same reasoning as
    // `osd_setup_generic_packed`'s own row-XOR during elimination —
    // it packs directly into `n.div_ceil(64)` word-XORs instead of `n`
    // per-byte ones, with no gather/scatter complication.
    let mut g_packed = [[0u64; OSD_WORDS]; OSD_MAX_N];
    let g_packed = &mut g_packed[..k];
    for (row, row_words) in g_packed.iter_mut().enumerate() {
        for col in 0..n {
            if g[row * n + col] != 0 {
                row_words[col / 64] |= 1 << (col % 64);
            }
        }
    }

    // ── Step 5: encode order-0 candidate (packed) ───────────────────
    let mut c_perm_packed = [0u64; OSD_WORDS];
    for r in 0..k {
        if mrb[r] == 1 {
            for w in 0..OSD_WORDS {
                c_perm_packed[w] ^= g_packed[r][w];
            }
        }
    }

    // Permuted hard-decisions and |LLR| — depend only on `perm`/`llr`,
    // both fixed for the rest of this call, so precomputing them once
    // here (O(n)) instead of inside `try_and_update` removes a branch,
    // an `.abs()` call and a double indirection (`llr[perm[col]]`)
    // from the ~166,650-call weighted-distance loop below (issue #306
    // follow-up: the previous per-call heap-alloc fix left this
    // redundant recomputation in place — same closure, different
    // waste). Bit-identical: `try_and_update` used to compute exactly
    // these two values fresh on every call from the same unchanging
    // `perm`/`llr`.
    let mut hdec_perm = [0u8; OSD_MAX_N];
    let hdec_perm = &mut hdec_perm[..n];
    let mut absrx_perm = [0.0f32; OSD_MAX_N];
    let absrx_perm = &mut absrx_perm[..n];
    for col in 0..n {
        hdec_perm[col] = if llr[perm[col]] > 0.0 { 1u8 } else { 0u8 };
        absrx_perm[col] = llr[perm[col]].abs();
    }

    // Inverse permutation: `inv_perm[i]` is the permuted-space column
    // holding unpermuted (systematic) position `i`. `decoded[i]` for
    // `i < k` only ever needs `cp[inv_perm[i]]` — this lets
    // `try_and_update` gather just the `k` bits `verify` needs instead
    // of scattering the full `n`-length codeword (and copying its
    // first `k`) on every call before even checking whether `verify`
    // will reject the candidate a moment later. `verify` (`check_crc14`
    // and its FST4/MSK144 equivalents) is a strong filter — a
    // 14..24-bit CRC rejects essentially every one of the ~166,650
    // wrong FST4 candidates — so this turns the previously
    // always-executed `O(n)` scatter into an `O(k)` gather for the
    // overwhelming majority of calls, deferring the `O(n)` codeword
    // build to the rare (effectively: only the true candidate) path
    // that actually needs it.
    let mut inv_perm = [0usize; OSD_MAX_N];
    let inv_perm = &mut inv_perm[..n];
    for (col, &p) in perm.iter().enumerate() {
        inv_perm[p] = col;
    }

    // Best-so-far, plus the scratch `try_and_update` writes each
    // candidate into before deciding whether it's an improvement.
    // Single closure (not a `try_candidate` + separate `update_best`
    // pair) so there's exactly one `FnMut` capturing all of these by
    // mutable reference, rather than two closures each needing to
    // borrow the other's captures — simpler for the borrow checker,
    // same logic as the previous two-closure version.
    let mut best_wd: Option<f32> = None;
    let mut best_codeword = [0u8; OSD_MAX_N];
    let mut best_decoded = [0u8; OSD_MAX_N];
    let mut scratch_c = [0u8; OSD_MAX_N];
    let mut scratch_decoded = [0u8; OSD_MAX_N];
    // `cp` is now `OSD_WORDS`-word packed (bit `col` lives at
    // `cp[col/64]` bit `col%64`) rather than one byte per bit — the
    // caller (the k1..k4 construction below) builds it via
    // `g_packed`'s word-XORs instead of `g`'s byte-XORs. The gather
    // step (`decoded[i] = bit(cp, inv_perm[i])`) stays `O(k)` either
    // way, just trading a byte load for a shift+mask; the scatter and
    // weighted-distance loops (still `O(n)`, still gated behind
    // `verify` exactly as before) are now one combined pass instead of
    // two, since both need the same per-column bit.
    let mut try_and_update = |cp: &[u64]| {
        let decoded = &mut scratch_decoded[..k];
        for (i, d) in decoded.iter_mut().enumerate() {
            let idx = inv_perm[i];
            *d = ((cp[idx / 64] >> (idx % 64)) & 1) as u8;
        }
        if let Some(f) = verify
            && !f(decoded)
        {
            return;
        }
        let c = &mut scratch_c[..n];
        let mut wd = 0.0f32;
        for col in 0..n {
            let bit = ((cp[col / 64] >> (col % 64)) & 1) as u8;
            c[perm[col]] = bit;
            if bit != hdec_perm[col] {
                wd += absrx_perm[col];
            }
        }
        if best_wd.is_none_or(|bd| wd < bd) {
            best_wd = Some(wd);
            best_codeword[..n].copy_from_slice(&scratch_c[..n]);
            best_decoded[..k].copy_from_slice(&scratch_decoded[..k]);
        }
    };

    // Order-0.
    try_and_update(&c_perm_packed);

    // Orders 1..ndeep: flip 1, 2, …, ndeep MRB bits. `c1`/`c2`/`c3`/`c4`
    // are packed now too — each is computed directly as a word-XOR of
    // its parent and one `g_packed` row (`OSD_WORDS`=4 XORs) instead
    // of a byte copy plus an `n`-element (up to 240) byte-XOR loop,
    // for every one of the ~166 650 order-3 combinations this search
    // makes for FST4.
    let mut c1_packed = [0u64; OSD_WORDS];
    let mut c2_packed = [0u64; OSD_WORDS];
    let mut c3_packed = [0u64; OSD_WORDS];
    let mut c4_packed = [0u64; OSD_WORDS];
    for k1 in 0..k {
        for w in 0..OSD_WORDS {
            c1_packed[w] = c_perm_packed[w] ^ g_packed[k1][w];
        }
        try_and_update(&c1_packed);
        if ndeep < 2 {
            continue;
        }
        for k2 in (k1 + 1)..k {
            for w in 0..OSD_WORDS {
                c2_packed[w] = c1_packed[w] ^ g_packed[k2][w];
            }
            try_and_update(&c2_packed);
            if ndeep < 3 {
                continue;
            }
            for k3 in (k2 + 1)..k {
                for w in 0..OSD_WORDS {
                    c3_packed[w] = c2_packed[w] ^ g_packed[k3][w];
                }
                try_and_update(&c3_packed);
                if ndeep >= 4 {
                    // See `k4_tail`'s doc comment above for which end
                    // of the reliability ordering each branch searches.
                    // `false` branch unchanged from before `k4_tail`
                    // existed — same gate, same range.
                    let (gate, k4_start, k4_end) = if k4_tail {
                        (k1 >= k.saturating_sub(k4_limit), k3 + 1, k)
                    } else {
                        (k3 + 1 < k4_limit, k3 + 1, k4_limit.min(k))
                    };
                    if gate {
                        for k4 in k4_start..k4_end {
                            for w in 0..OSD_WORDS {
                                c4_packed[w] = c3_packed[w] ^ g_packed[k4][w];
                            }
                            try_and_update(&c4_packed);
                        }
                    }
                }
            }
        }
    }

    // ── Step 6: return best ─────────────────────────────────────────
    best_wd?;
    let codeword = &best_codeword[..n];
    let decoded = &best_decoded[..k];
    let mut hard_errors = 0u32;
    for i in 0..n {
        if (codeword[i] == 1) != (llr[i] > 0.0) {
            hard_errors += 1;
        }
    }
    let mut message77 = [0u8; 77];
    message77.copy_from_slice(&decoded[..77]);
    Some(OsdResult {
        message77,
        info: decoded.to_vec(),
        codeword: codeword.to_vec(),
        hard_errors,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Verify that ldpc_encode produces codewords that satisfy ALL 83 parity
    /// check equations stored in the NM/NRW tables.
    ///
    /// If this test fails, GEN_PARITY is inconsistent with the check matrix —
    /// confirmed encoder bug.
    #[test]
    fn verify_ldpc_encode_parity() {
        use super::super::LDPC_M;
        use super::super::tables::{NM, NRW};

        // Test with several different info vectors to catch row-specific bugs.
        let test_infos: &[[u8; LDPC_K]] = &[
            [1u8; LDPC_K], // all ones
            {
                let mut v = [0u8; LDPC_K];
                for i in (0..LDPC_K).step_by(2) {
                    v[i] = 1;
                }
                v
            }, // alternating
            {
                let mut v = [0u8; LDPC_K];
                // first 77 bits = 1 (message), last 14 = 0 (CRC placeholder)
                for i in 0..77 {
                    v[i] = 1;
                }
                v
            },
        ];

        for (t, info) in test_infos.iter().enumerate() {
            let cw = ldpc_encode(info);
            for j in 0..LDPC_M {
                let n = NRW[j] as usize;
                let check: u8 = NM[j][..n]
                    .iter()
                    .map(|&i| cw[i as usize])
                    .fold(0u8, |acc, b| acc ^ b);
                assert_eq!(
                    check, 0,
                    "GEN_PARITY inconsistency: parity check row {} failed for test info #{} — encoder bug confirmed",
                    j, t
                );
            }
        }
    }
}

#[cfg(test)]
mod packed_setup_differential {
    use super::*;
    use crate::fec::ldpc::params::{Ldpc128_90Params, Ldpc240_101Params};

    /// The setup `osd_decode_generic` used before packing, preserved
    /// here verbatim as the reference `osd_setup_generic_packed` is
    /// checked against — the same "keep the old implementation as the
    /// diff target" pattern `wspr::osd::osd_decode` is kept for.
    pub(super) fn osd_setup_generic_reference<P: LdpcParams>(
        llr: &[f32],
    ) -> Option<(Vec<usize>, Vec<u8>, Vec<usize>)> {
        let n = P::N;
        let k = P::K;

        let mut perm: Vec<usize> = (0..n).collect();
        perm.sort_unstable_by(|&a, &b| {
            llr[b]
                .abs()
                .partial_cmp(&llr[a].abs())
                .unwrap_or(core::cmp::Ordering::Equal)
        });

        let mut g: Vec<u8> = vec![0u8; k * n];
        for row in 0..k {
            for col in 0..n {
                let j = perm[col];
                g[row * n + col] = if j < k {
                    (row == j) as u8
                } else {
                    P::gen_parity(j - k, row)
                };
            }
        }

        let mut pivot_col: Vec<usize> = vec![0; k];
        let mut pivot_row = 0usize;
        for col in 0..n {
            if pivot_row >= k {
                break;
            }
            let mut found: Option<usize> = None;
            for r in pivot_row..k {
                if g[r * n + col] != 0 {
                    found = Some(r);
                    break;
                }
            }
            if let Some(r) = found {
                if r != pivot_row {
                    for c in 0..n {
                        g.swap(r * n + c, pivot_row * n + c);
                    }
                }
                for r2 in 0..k {
                    if r2 != pivot_row && g[r2 * n + col] != 0 {
                        for c in 0..n {
                            g[r2 * n + c] ^= g[pivot_row * n + c];
                        }
                    }
                }
                pivot_col[pivot_row] = col;
                pivot_row += 1;
            }
        }

        if pivot_row < k {
            return None;
        }
        Some((perm, g, pivot_col))
    }

    /// Deterministic xorshift32 — no external RNG dependency, and
    /// reproducible across runs so a failure is re-diagnosable.
    struct Xorshift32(u32);
    impl Xorshift32 {
        fn next_f32(&mut self) -> f32 {
            self.0 ^= self.0 << 13;
            self.0 ^= self.0 >> 17;
            self.0 ^= self.0 << 5;
            (self.0 % 4000) as f32 / 100.0 - 20.0 // spread over [-20, 20)
        }
    }

    /// Real codewords (valid, so elimination never degenerates by
    /// construction) plus synthetic LLR noise, covering both concrete
    /// `LdpcParams` the generic path serves. Not a hand-picked case:
    /// `REPS` distinct random info vectors × independent noise draws
    /// per protocol.
    fn check_matches<P: LdpcParams>(seed: u32) {
        const REPS: usize = 200;
        let mut rng = Xorshift32(seed);
        let mut mismatches = 0usize;
        for t in 0..REPS {
            let mut info = alloc::vec![0u8; P::K];
            for b in info.iter_mut() {
                rng.0 ^= rng.0 << 13;
                rng.0 ^= rng.0 >> 17;
                rng.0 ^= rng.0 << 5;
                *b = (rng.0 & 1) as u8;
            }
            let mut cw = alloc::vec![0u8; P::N];
            ldpc_encode_generic::<P>(&info, &mut cw);

            let llr: alloc::vec::Vec<f32> = cw
                .iter()
                .map(|&b| {
                    let noise = rng.next_f32();
                    // Sign convention matches `mrb`'s: bit=1 -> llr>0
                    // (`mrb[r] = if llr[orig] > 0.0 { 1 } else { 0 }`).
                    (if b == 1 { 10.0 } else { -10.0 }) + noise
                })
                .collect();

            let reference = osd_setup_generic_reference::<P>(&llr);
            let packed = osd_setup_generic_packed::<P>(&llr);
            if reference != packed {
                mismatches += 1;
                eprintln!("trial {t}: reference={reference:?}\npacked={packed:?}");
            }
        }
        assert_eq!(mismatches, 0, "{mismatches}/{REPS} trials diverged");
    }

    #[test]
    fn matches_reference_ldpc128_90() {
        check_matches::<Ldpc128_90Params>(0xC0FF_EE01);
    }

    #[test]
    fn matches_reference_ldpc240_101() {
        check_matches::<Ldpc240_101Params>(0xC0FF_EE02);
    }

    #[test]
    fn matches_reference_ldpc174_91() {
        check_matches::<Ldpc174_91Params>(0xC0FF_EE03);
    }

    /// End-to-end, not just the setup: `osd_decode_generic` itself
    /// (packed setup + unchanged encode/search/verify) must recover
    /// the exact transmitted info bits from a clean (noise-free)
    /// codeword — the property the setup differential can't see on
    /// its own, since a setup bug that happens to still produce *some*
    /// valid RREF wouldn't necessarily show up as a `(perm, g,
    /// pivot_col)` mismatch against a differently-parameterised
    /// reference call.
    /// A locked bit is not flipped by the masked `npre1` search: a clean
    /// codeword with one bit locked to the wrong value comes back from the
    /// unmasked search (one flip repairs it) and does not from the masked one
    /// (`osd174_91.f90`: `if(any(iand(apmaskr(1:k),mi).eq.1)) cycle`).
    #[test]
    fn masked_npre1_does_not_flip_a_locked_bit() {
        use crate::fec::ldpc::bp::append_crc14;
        let mut msg = [0u8; 77];
        for (i, b) in msg.iter_mut().enumerate() {
            *b = ((i * 5 + 1) % 3 == 0) as u8;
        }
        let info = append_crc14(&msg);
        let cw = ldpc_encode(&info);
        let mut llr = [0f32; LDPC_N];
        for (l, &b) in llr.iter_mut().zip(cw.iter()) {
            *l = if b == 1 { 8.0 } else { -8.0 };
        }
        // Lock bit 5 to the wrong value, as strongly as anything else here.
        let wrong = if cw[5] == 1 { -20.0 } else { 20.0 };
        llr[5] = wrong;
        let mut mask = [false; LDPC_N];
        mask[5] = true;

        let free = crate::fec::ldpc::osd_npre::osd174_91(
            &llr,
            crate::fec::ldpc::osd_npre::NDEEP2_174_91,
            None,
        )
        .expect("one flip repairs the bit");
        assert_eq!(free.codeword.as_slice(), cw.as_slice());

        match crate::fec::ldpc::osd_npre::osd174_91(
            &llr,
            crate::fec::ldpc::osd_npre::NDEEP2_174_91,
            Some(&mask),
        ) {
            None => {}
            Some(r) => assert_eq!(
                r.codeword[5] == 1,
                wrong > 0.0,
                "the locked bit was flipped"
            ),
        }
    }

    #[test]
    fn osd_decode_generic_recovers_clean_codeword() {
        let info: alloc::vec::Vec<u8> = (0..Ldpc128_90Params::K)
            .map(|i| (i % 3 == 0) as u8)
            .collect();
        let mut cw = alloc::vec![0u8; Ldpc128_90Params::N];
        ldpc_encode_generic::<Ldpc128_90Params>(&info, &mut cw);
        let llr: alloc::vec::Vec<f32> = cw
            .iter()
            .map(|&b| if b == 1 { 10.0 } else { -10.0 })
            .collect();
        let result =
            osd_decode_generic::<Ldpc128_90Params>(&llr, 2, Ldpc128_90Params::K, None, false)
                .expect("clean codeword must decode");
        assert_eq!(result.info, info);
    }

    // ── PartialCrc (FST4's Keff = 91) ───────────────────────────────

    fn fst4_partial_crc() -> PartialCrc {
        PartialCrc {
            keff: 91,
            with_crc: crate::fec::ldpc240_101::append_crc24,
        }
    }

    /// xorshift64* uniform in (0, 1); deterministic, no dev-dependency.
    fn next_uniform(state: &mut u64) -> f32 {
        *state ^= *state >> 12;
        *state ^= *state << 25;
        *state ^= *state >> 27;
        let v = state.wrapping_mul(0x2545_F491_4F6C_DD1D) >> 40;
        (v as f32 + 0.5) / 16_777_216.0
    }

    fn random_message(state: &mut u64) -> [u8; 77] {
        let mut m = [0u8; 77];
        for b in m.iter_mut() {
            *b = (next_uniform(state) > 0.5) as u8;
        }
        m
    }

    /// The generator rows must span every CRC-valid codeword: a clean one has to
    /// come back with the message that was sent, through both `npre` depths.
    #[test]
    fn partial_crc_decodes_a_clean_codeword() {
        use crate::fec::ldpc240_101::{append_crc24, check_crc24};
        let mut state = 0x9E37_79B9_7F4A_7C15u64;
        for _ in 0..8 {
            let msg = random_message(&mut state);
            let info = append_crc24(&msg);
            let mut cw = alloc::vec![0u8; Ldpc240_101Params::N];
            ldpc_encode_generic::<Ldpc240_101Params>(&info, &mut cw);
            let llr: alloc::vec::Vec<f32> = cw
                .iter()
                .map(|&b| if b == 1 { 8.0 } else { -8.0 })
                .collect();
            for (ntau, npre2) in [(0, false), (14, true)] {
                let r = crate::fec::ldpc::osd_npre::osd_npre::<Ldpc240_101Params>(
                    &llr,
                    crate::fec::ldpc::osd_npre::NpreDepth {
                        ntheta: 12,
                        npre2,
                        ntau,
                    },
                    Some(fst4_partial_crc()),
                    None,
                    Some(check_crc24),
                )
                .expect("a clean CRC-valid codeword must decode");
                assert_eq!(r.info, info);
                assert_eq!(r.message77, msg);
            }
        }
    }

    /// A locked bit is not flipped by the masked `npre1` search over
    /// [`Ldpc240_101Params`] — [`osd_npre`](crate::fec::ldpc::osd_npre::osd_npre)'s
    /// counterpart to `masked_npre1_does_not_flip_a_locked_bit` above
    /// (issue #465): a clean codeword with one bit locked to the wrong
    /// value comes back from the unmasked search (one flip repairs it)
    /// and does not from the masked one (`osd240_101.f90:192`).
    #[test]
    fn masked_npre1_does_not_flip_a_locked_bit_ldpc240_101() {
        use crate::fec::ldpc240_101::append_crc24;
        let msg = random_message(&mut 0x1234_5678_9ABC_DEF0u64);
        let info = append_crc24(&msg);
        let mut cw = alloc::vec![0u8; Ldpc240_101Params::N];
        ldpc_encode_generic::<Ldpc240_101Params>(&info, &mut cw);
        let mut llr: alloc::vec::Vec<f32> = cw
            .iter()
            .map(|&b| if b == 1 { 8.0 } else { -8.0 })
            .collect();
        // Lock bit 5 to the wrong value, as strongly as anything else here.
        let wrong = if cw[5] == 1 { -20.0 } else { 20.0 };
        llr[5] = wrong;
        let mut mask = alloc::vec![false; Ldpc240_101Params::N];
        mask[5] = true;

        let free = crate::fec::ldpc::osd_npre::osd_npre::<Ldpc240_101Params>(
            &llr,
            crate::fec::ldpc::osd_npre::NpreDepth {
                ntheta: 12,
                npre2: false,
                ntau: 0,
            },
            Some(fst4_partial_crc()),
            None,
            None,
        )
        .expect("one flip repairs the bit");
        assert_eq!(free.codeword.as_slice(), cw.as_slice());

        match crate::fec::ldpc::osd_npre::osd_npre::<Ldpc240_101Params>(
            &llr,
            crate::fec::ldpc::osd_npre::NpreDepth {
                ntheta: 12,
                npre2: false,
                ntau: 0,
            },
            Some(fst4_partial_crc()),
            Some(&mask),
            None,
        ) {
            None => {}
            Some(r) => assert_eq!(
                r.codeword[5] == 1,
                wrong > 0.0,
                "the locked bit was flipped"
            ),
        }
    }

    /// The reason `PartialCrc` exists: on the same noisy LLRs, the 91-bit
    /// subcode recovers the sent message more often than the full 101-bit code,
    /// which is what `decode240_101(Keff = 91)` does and this crate did not.
    /// OSD alone (no BP in front), ndeep 2, BPSK/AWGN, verify on the winner.
    #[test]
    fn partial_crc_recovers_more_than_the_full_code() {
        use crate::fec::ldpc240_101::{append_crc24, check_crc24};
        let amp = 0.95f32;
        let draws = 300;
        let mut state = 0xD1B5_4A32_D192_ED03u64;
        let mut ok = [0u32; 2];
        for _ in 0..draws {
            let msg = random_message(&mut state);
            let info = append_crc24(&msg);
            let mut cw = alloc::vec![0u8; Ldpc240_101Params::N];
            ldpc_encode_generic::<Ldpc240_101Params>(&info, &mut cw);
            let llr: alloc::vec::Vec<f32> = cw
                .iter()
                .map(|&b| {
                    let (u1, u2) = (next_uniform(&mut state), next_uniform(&mut state));
                    let noise = (-2.0 * u1.ln()).sqrt() * (core::f32::consts::TAU * u2).cos();
                    2.0 * (amp * (2.0 * b as f32 - 1.0) + noise)
                })
                .collect();
            for (i, pc) in [Some(fst4_partial_crc()), None].into_iter().enumerate() {
                if let Some(r) = crate::fec::ldpc::osd_npre::osd_npre::<Ldpc240_101Params>(
                    &llr,
                    crate::fec::ldpc::osd_npre::NpreDepth {
                        ntheta: 12,
                        npre2: false,
                        ntau: 0,
                    },
                    pc,
                    None,
                    Some(check_crc24),
                ) && r.message77 == msg
                {
                    ok[i] += 1;
                }
            }
        }
        // 115 against 70 of 300 when measured (2026-09-25): the margin is wide
        // enough that a libm difference in `ln`/`cos` cannot flip it.
        assert!(
            ok[0] * 10 >= ok[1] * 13,
            "Keff=91 recovered {} of {draws}, Keff=101 recovered {}",
            ok[0],
            ok[1]
        );
    }
}

