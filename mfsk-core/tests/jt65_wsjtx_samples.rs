//! JT65 golden-recording validation: recall, precision and SNR.
//!
//! JT65 was the only implemented protocol with **no golden decode test
//! at all**. Its two existing test files are an AWGN sweep (`#[ignore]`,
//! statistics-only) and an SNR-tracking check, so nothing asserted that
//! a specific recording produces specific messages — and nothing at all
//! bounded false decodes.
//!
//! ## Why this uses a `jt65sim` recording and not an off-air one
//!
//! WSJT-X ships JT65 samples only under `samples/JT65/JT65B/`, and this
//! crate implements **JT65A** — `Jt65::TONE_SPACING_HZ` is
//! `12000/4460 ≈ 2.69 Hz`, where JT65B is twice that. Verified rather
//! than assumed: the JT65B recording that real `jt9 -6 -b B` decodes
//! (`000000_0004.wav` → `K1ABC G4XYZ IO91`) yields **0 decodes** from
//! `decode_scan` and `decode_scan_chase` alike. There is no off-air
//! JT65A recording available, which is why this test never existed.
//!
//! So the golden here is generated by WSJT-X's own `jt65sim`, which
//! makes it *reference-produced* rather than off-air — a weaker
//! provenance, stated plainly. Two things keep it honest:
//!
//! - **It is bit-reproducible.** `jt65sim -m A -n 5 -s '\-18' -f 1 -p`
//!   (`-p` = do not seed the PRNGs) emits an identical file on every
//!   run; confirmed by md5 across regenerations. So the committed WAV
//!   is exactly what that command produces, and anyone can rebuild it.
//! - **Its expected output is the reference decoder's.** Real
//!   `jt9 -6 -p 60 -b A` reports `K1ABC W9XYZ EN37` at −19 dB on this
//!   file (injected −18), which is what the SNR bound below is written
//!   against.
//!
//! `jt65sim` places five copies of the same message at 700/1100/1500/
//! 1900/2300 Hz. Real `jt9` prints one — it de-duplicates by callsign —
//! while this crate reports each frequency separately, so recall is
//! counted in frequencies rather than in distinct messages.

#![cfg(all(feature = "jt65", any(feature = "fft-rustfft", feature = "fft-extern")))]

use mfsk_core::jt65::decode_scan;
use mfsk_core::jt65::search::SearchParams;

#[allow(dead_code)]
mod common;
use common::golden::{DecodeView, GoldenEntry, GoldenSet, Tolerances, assert_golden};
use common::load_wav_f32_opt;

/// The one message `jt65sim` was told to transmit, and the only text
/// any decode may carry.
const MSG: &str = "K1ABC W9XYZ EN37";
/// Frequencies `jt65sim` placed it at.
const CARRIERS: [f32; 5] = [700.0, 1100.0, 1500.0, 1900.0, 2300.0];
/// Injected S/N in the 2500 Hz reference bandwidth; real `jt9` reports
/// −19 on this file.
const REFERENCE_SNR_DB: f32 = -19.0;

fn audio() -> Option<Vec<f32>> {
    let path = common::corpus::golden_path("jt65/jt65a_5sig_m18.wav")?;
    load_wav_f32_opt(&path)
}

fn decodes() -> Option<Vec<mfsk_core::jt65::Jt65Result>> {
    let a = audio()?;
    let params = SearchParams {
        freq_min_hz: 300.0,
        freq_max_hz: 2700.0,
        ..SearchParams::default()
    };
    Some(decode_scan(&a, 12_000, 0, &params))
}

/// Recall and precision together, via the shared helper.
///
/// Recall floor is 4 of the 5 carriers: this crate currently misses
/// the 1500 Hz copy. Raising the floor is a sensitivity win; lowering
/// it is a regression. Precision budget is **0** — any text other than
/// `MSG` is invented, since the file contains exactly one message.
#[test]
fn jt65_golden_recall_and_precision() {
    let Some(d) = decodes() else {
        eprintln!("skipping: JT65 golden recording not found");
        return;
    };

    // One entry per carrier: `assert_golden` matches on (msg, freq),
    // so five entries with the same text count the five copies.
    let expected: Vec<GoldenEntry> = CARRIERS
        .iter()
        .map(|&f| GoldenEntry {
            msg: MSG,
            freq_hz: Some(f),
            dt_sec: None,
            snr_db: None,
        })
        .collect();

    assert_golden(
        &d,
        &GoldenSet {
            name: "JT65A jt65sim 5×-18 dB",
            expected: Box::leak(expected.into_boxed_slice()),
            min_hits: 4,
            max_extra: 0,
        },
        Tolerances {
            freq_hz: 5.0,
            ..Tolerances::default()
        },
        |r| DecodeView {
            msg: r.message.to_string(),
            freq_hz: r.freq_hz,
            dt_sec: r.start_sample as f32 / 12_000.0,
            snr_db: Some(r.snr_db),
        },
    );
}

/// Reported SNR must track the reference decoder's on the same file.
///
/// Separate from the recall/precision test because `assert_golden`
/// matches SNR per distinct message text, and this file's five decodes
/// all share one — checking each carrier individually says more.
/// Tolerance is ±4 dB, the same budget `jt65_sweep`'s injected-SNR
/// check uses, and wide enough to survive corpus regeneration without
/// admitting the ~32 dB class of error that JT9's SNR bug turned out
/// to be.
#[test]
fn jt65_golden_snr_matches_reference_decoder() {
    const SNR_TOL_DB: f32 = 4.0;

    let Some(d) = decodes() else {
        eprintln!("skipping: JT65 golden recording not found");
        return;
    };
    assert!(!d.is_empty(), "no JT65 decodes to check SNR against");

    let mut bad = Vec::new();
    for r in &d {
        let err = r.snr_db - REFERENCE_SNR_DB;
        eprintln!(
            "  {:7.1} Hz  reported {:+.1} dB  reference {REFERENCE_SNR_DB:+.1}  err {err:+.1}",
            r.freq_hz, r.snr_db
        );
        if err.abs() > SNR_TOL_DB {
            bad.push(format!(
                "{:.0} Hz: {:+.1} dB (err {err:+.1})",
                r.freq_hz, r.snr_db
            ));
        }
    }
    assert!(
        bad.is_empty(),
        "JT65 reported SNR is more than ±{SNR_TOL_DB} dB from real jt9's \
         {REFERENCE_SNR_DB:+.1} dB on this file: {bad:?}"
    );
}
